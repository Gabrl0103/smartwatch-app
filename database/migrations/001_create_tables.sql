-- Tablas de Rumbo. Usuario único fijo (sin autenticación).
-- Nombres en inglés; ver el modelo de datos en docs/REQUIREMENTS.md.

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

-- El id lo genera el reloj (UUID) para que registrarlo dos veces no duplique filas.
CREATE TABLE devices (
    id VARCHAR(64) PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    type TEXT NOT NULL DEFAULT 'wear_os',
    registered_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_devices_user_id ON devices (user_id);

CREATE TABLE saved_places (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    lat DOUBLE PRECISION NOT NULL CHECK (lat BETWEEN -90 AND 90),
    lng DOUBLE PRECISION NOT NULL CHECK (lng BETWEEN -180 AND 180),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_saved_places_user_id ON saved_places (user_id);

CREATE TABLE routes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    origin_lat DOUBLE PRECISION NOT NULL,
    origin_lng DOUBLE PRECISION NOT NULL,
    destination_lat DOUBLE PRECISION NOT NULL,
    destination_lng DOUBLE PRECISION NOT NULL,
    destination_name TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed', 'cancelled'))
);
CREATE INDEX idx_routes_user_id ON routes (user_id);

-- La restricción única sobre (route_id, step_order) también sirve de índice por route_id.
CREATE TABLE route_steps (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id INTEGER NOT NULL REFERENCES routes (id) ON DELETE CASCADE,
    step_order INTEGER NOT NULL,
    maneuver TEXT NOT NULL CHECK (maneuver IN ('left', 'right', 'straight', 'arrive')),
    distance_to_next_m DOUBLE PRECISION NOT NULL,
    lat DOUBLE PRECISION NOT NULL,
    lng DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_route_steps_route_order UNIQUE (route_id, step_order)
);

CREATE TABLE voice_commands (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    transcribed_text TEXT NOT NULL,
    intent TEXT NOT NULL CHECK (intent IN ('navigate', 'ask', 'cancel', 'repeat')),
    extracted_destination TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_voice_commands_user_id ON voice_commands (user_id);

-- Log de vibraciones para la demo; el paso es opcional (vibraciones sin ruta conocida).
CREATE TABLE vibration_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_step_id INTEGER REFERENCES route_steps (id) ON DELETE SET NULL,
    pattern TEXT NOT NULL,
    emitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_vibration_events_route_step_id ON vibration_events (route_step_id);
